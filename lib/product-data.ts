import { PhoneProduct, AccessoryProduct } from './types';

export function getPhonePrice(
  phone: PhoneProduct,
  storage?: string
): { price: number; originalPrice?: number } {
  const targetStorage = storage || phone.selectedStorage || (phone.storageOptions && phone.storageOptions[0]);
  if (phone.storagePrices && targetStorage && phone.storagePrices[targetStorage]) {
    return phone.storagePrices[targetStorage];
  }
  return { price: phone.price, originalPrice: phone.originalPrice };
}

export function getAccessoryPrice(
  acc: AccessoryProduct,
  capacity?: string
): { price: number; originalPrice?: number } {
  const targetCapacity = capacity || acc.selectedCapacity || (acc.capacityOptions && acc.capacityOptions[0]);
  if (acc.capacityPrices && targetCapacity && acc.capacityPrices[targetCapacity]) {
    return acc.capacityPrices[targetCapacity];
  }
  return { price: acc.price, originalPrice: acc.originalPrice };
}

